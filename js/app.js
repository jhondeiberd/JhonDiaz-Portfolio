/**
 * Portfolio front-end logic (no framework, no build step for this file).
 *
 * Regions (fold them in your editor with "#region"):
 *   1. Setup and helpers         shared state, DOM helpers, safe localStorage access
 *   2. Language (EN / FR / ES)   applies translations from the dictionaries in js/i18n-*.js
 *   3. Rotating role titles      hero job titles that cycle automatically
 *   4. Theme (light / dark)      toggle + follows the system preference until the user chooses
 *   5. Navigation                mobile menu and highlighting of the active section
 *   6. Home / Back to top        always scrolls to the very top
 *   7. Project dialog            modal with YouTube embed, local video or image
 *   8. Visit counter             talks to /api/visits
 *   9. Contact form              validation + POST to /api/contact with a mailto fallback
 *  10. Start-up
 *
 * Translation model: the English text lives in index.html. Elements that can be translated carry
 * data-i18n="key" (or data-i18n-attr="attr:key;attr:key" for attributes). French and Spanish come
 * from window.I18N_FR / window.I18N_ES; short UI messages come from window.I18N_JS as [en, fr, es].
 * All three files are generated by tools/build.py, so do not edit them by hand.
 */
(function () {
  'use strict';

  // #region 1. Setup and helpers
  var root = document.documentElement;
  var DICT = { fr: window.I18N_FR || {}, es: window.I18N_ES || {} };
  var LOCALE = { en: 'en-CA', fr: 'fr-CA', es: 'es' }; // used to format numbers
  var JSS = window.I18N_JS || {}; // UI messages: name -> [en, fr, es]
  var EMAIL = 'jhondeiberd@gmail.com'; // mailto fallback address

  // localStorage can throw (private mode, blocked cookies), so every write goes through here.
  function store(k, v) {
    try {
      localStorage.setItem(k, v);
    } catch (e) {}
  }
  function $(s, c) {
    return (c || document).querySelector(s);
  }
  function $$(s, c) {
    return Array.prototype.slice.call((c || document).querySelectorAll(s));
  }
  // #endregion

  // #region 2. Language (EN / FR / ES)
  // The head script in index.html already set <html lang> from localStorage or the browser language.
  var lang = ['fr', 'es'].indexOf(root.getAttribute('lang')) > -1 ? root.getAttribute('lang') : 'en';
  var original = new Map(); // element -> original English innerHTML, so we can switch back to English

  // tr(): UI message by name in the current language. text(): page text by key, English fallback.
  function tr(name) {
    var e = JSS[name];
    return e ? e[{ en: 0, fr: 1, es: 2 }[lang]] : name;
  }
  function text(key, enFallback) {
    return lang !== 'en' && DICT[lang][key] ? DICT[lang][key] : enFallback;
  }

  // Re-renders everything that depends on the language. Safe to call as often as needed.
  function applyLanguage() {
    // Text content
    $$('[data-i18n]').forEach(function (el) {
      if (!original.has(el)) original.set(el, el.innerHTML);
      var key = el.getAttribute('data-i18n');
      el.innerHTML = lang !== 'en' && DICT[lang][key] ? DICT[lang][key] : original.get(el);
    });
    // Attributes (alt, aria-label, placeholder...): data-i18n-attr="alt:key;placeholder:key"
    $$('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr')
        .split(';')
        .forEach(function (pair) {
          var p = pair.split(':'),
            attr = p[0],
            key = p[1];
          var ek = '__en_' + attr; // remember the English value on the element
          if (el[ek] === undefined) el[ek] = el.getAttribute(attr);
          el.setAttribute(attr, lang !== 'en' && DICT[lang][key] ? DICT[lang][key] : el[ek]);
        });
    });
    root.setAttribute('lang', lang);
    // The resume buttons download the PDF that matches the language being displayed
    $$('a[data-cv]').forEach(function (a) {
      var f = 'Jhon_Diaz_CV_' + lang.toUpperCase() + '.pdf';
      a.setAttribute('href', 'assets/docs/' + f);
      a.setAttribute('download', f);
    });
    $$('.lang__btn').forEach(function (b) {
      b.setAttribute('aria-pressed', String(b.getAttribute('data-lang') === lang));
    });
    // Pieces of UI whose text is set from JavaScript
    var send = $('#submitButton span');
    if (send && !$('#submitButton').disabled) send.textContent = tr('send');
    var v = $('#visitLabel');
    if (v) v.textContent = tr('visits');
    var menu = $('#menuToggle');
    if (menu)
      menu.setAttribute(
        'aria-label',
        tr($('#siteNav').classList.contains('is-open') ? 'menu_close' : 'menu_open'),
      );
    var cl = $('#projectClose');
    if (cl) cl.setAttribute('aria-label', tr('close'));
    updateThemeLabel();
    if (typeof labelDots === 'function') labelDots();
    var dlg = $('#projectDialog');
    if (dlg && dlg.open && current) fillDialog(current); // re-render an open dialog
    var vc = $('#visitCount');
    if (vc && vc.dataset.n) vc.textContent = Number(vc.dataset.n).toLocaleString(LOCALE[lang]);
    var fs = $('#formStatus');
    if (fs && fs.dataset.msg) fs.firstChild && (fs.firstChild.textContent = tr(fs.dataset.msg));
  }

  $$('.lang__btn').forEach(function (b) {
    b.addEventListener('click', function () {
      lang = ['fr', 'es'].indexOf(b.getAttribute('data-lang')) > -1 ? b.getAttribute('data-lang') : 'en';
      store('lang', lang);
      applyLanguage();
    });
  });
  // #endregion

  // #region 3. Rotating role titles
  // All titles are in the DOM, stacked in one CSS grid cell; only .is-active is visible (see css, region "Role rotator").
  // The rotation keeps running under prefers-reduced-motion (the CSS then swaps instantly instead of sliding)
  // and pauses while the tab is hidden. Clicking a dot picks a role and resumes the rotation after 7 s.
  var ROLE_INTERVAL_MS = 2200;
  var roles = $$('.role'),
    dots = $('#roleDots'),
    roleIdx = 0,
    roleTimer = null,
    resumeTimer = null,
    dotBtns = [];

  function showRole(i) {
    roleIdx = i;
    roles.forEach(function (r, k) {
      r.classList.toggle('is-active', k === i);
      r.setAttribute('aria-hidden', String(k !== i));
    });
    dotBtns.forEach(function (d, k) {
      d.classList.toggle('is-active', k === i);
      d.setAttribute('aria-current', String(k === i));
    });
  }
  // Each dot is labelled with the title it selects (and re-labelled when the language changes).
  function labelDots() {
    dotBtns.forEach(function (d, k) {
      d.setAttribute('aria-label', $('.role__title', roles[k]).textContent);
    });
  }
  function stopRoles() {
    if (roleTimer) {
      clearInterval(roleTimer);
      roleTimer = null;
    }
  }
  function startRoles() {
    if (roleTimer || document.hidden || roles.length < 2) return;
    roleTimer = setInterval(function () {
      showRole((roleIdx + 1) % roles.length);
    }, ROLE_INTERVAL_MS);
  }
  if (roles.length && dots) {
    roles.forEach(function (r, k) {
      var b = document.createElement('button');
      b.type = 'button';
      b.className = 'roles__dot';
      b.addEventListener('click', function () {
        showRole(k);
        stopRoles();
        clearTimeout(resumeTimer);
        resumeTimer = setTimeout(startRoles, 7000);
      });
      dots.appendChild(b);
      dotBtns.push(b);
    });
    showRole(0);
    labelDots();
    startRoles();
    document.addEventListener('visibilitychange', function () {
      if (document.hidden) stopRoles();
      else startRoles();
    });
  }
  // #endregion

  // #region 4. Theme (light / dark)
  // The head script sets data-theme before first paint (no flash). Here we only handle changes.
  function updateThemeLabel() {
    var b = $('#themeToggle');
    if (!b) return;
    b.setAttribute(
      'aria-label',
      tr(root.getAttribute('data-theme') === 'dark' ? 'theme_to_light' : 'theme_to_dark'),
    );
  }
  $('#themeToggle').addEventListener('click', function () {
    var next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    root.setAttribute('data-theme', next);
    store('theme', next);
    updateThemeLabel();
  });
  // Until the visitor chooses a theme, follow the operating system when it changes.
  try {
    window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', function (e) {
      var saved = null;
      try {
        saved = localStorage.getItem('theme');
      } catch (x) {}
      if (!saved) {
        root.setAttribute('data-theme', e.matches ? 'dark' : 'light');
        updateThemeLabel();
      }
    });
  } catch (e) {}
  // #endregion

  // #region 5. Navigation (mobile menu + active section)
  // Below 1140 px the CSS turns the nav into a drop-down opened by the hamburger button.
  var nav = $('#siteNav'),
    menuBtn = $('#menuToggle');
  function setMenu(open) {
    nav.classList.toggle('is-open', open);
    menuBtn.setAttribute('aria-expanded', String(open));
    menuBtn.setAttribute('aria-label', tr(open ? 'menu_close' : 'menu_open'));
  }
  menuBtn.addEventListener('click', function () {
    setMenu(!nav.classList.contains('is-open'));
  });
  $$('.nav__link').forEach(function (a) {
    a.addEventListener('click', function () {
      setMenu(false);
    });
  });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') setMenu(false);
  });

  // Highlights the tab of the section that crosses the middle of the viewport.
  // A link may name its section with data-target (the Home tab points to the hero, not to #top).
  if ('IntersectionObserver' in window) {
    var links = {};
    $$('.nav__link').forEach(function (a) {
      links[a.getAttribute('data-target') || a.getAttribute('href').slice(1)] = a;
    });
    var io = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (en) {
          if (!en.isIntersecting) return;
          Object.keys(links).forEach(function (k) {
            links[k].classList.toggle('is-active', k === en.target.id);
          });
        });
      },
      { rootMargin: '-45% 0px -50% 0px' },
    );
    Object.keys(links).forEach(function (id) {
      var s = document.getElementById(id);
      if (s) io.observe(s);
    });
  }
  // #endregion

  // #region 6. Home / Back to top
  // Plain "#top" anchors can stop short because of the sticky header, so scroll to y = 0 explicitly.
  $$('a[href="#top"]').forEach(function (a) {
    a.addEventListener('click', function (e) {
      e.preventDefault();
      var smooth = !(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
      window.scrollTo({ top: 0, behavior: smooth ? 'smooth' : 'auto' });
      try {
        history.replaceState(null, '', location.pathname + location.search);
      } catch (x) {} // keep the URL clean
      setMenu(false);
    });
  });
  // #endregion

  // #region 7. Project dialog
  // Every project card is a button carrying its data in data-* attributes (generated by tools/build.py):
  //   data-title(-key), data-desc(-key)  text and its translation key
  //   data-type                          "video" or "image"
  //   data-youtube                       YouTube video id; when set it wins over the local file
  //   data-media / data-poster           local mp4 (or image) and its poster
  //   data-code                          optional source-code URL
  var dlg = $('#projectDialog'),
    current = null;

  function fillDialog(btn) {
    var d = btn.dataset;
    $('#projectTitle').textContent = text(d.titleKey, d.title);
    $('#projectDesc').textContent = text(d.descKey, d.desc);
    var media = $('#projectMedia');
    media.textContent = '';
    var label = tr('demo_label');
    if (d.type === 'video' && d.youtube) {
      // youtube-nocookie = privacy-enhanced mode (no tracking cookies until the visitor plays it)
      var f = document.createElement('iframe');
      f.src = 'https://www.youtube-nocookie.com/embed/' + encodeURIComponent(d.youtube) + '?rel=0';
      f.title = label;
      f.allow = 'accelerometer; encrypted-media; picture-in-picture; fullscreen';
      f.referrerPolicy = 'strict-origin-when-cross-origin';
      f.allowFullscreen = true;
      media.appendChild(f);
    } else if (d.type === 'video') {
      var v = document.createElement('video');
      v.src = d.media;
      v.poster = d.poster;
      v.controls = true;
      v.playsInline = true;
      v.preload = 'metadata';
      v.setAttribute('aria-label', label);
      media.appendChild(v);
    } else {
      var im = document.createElement('img');
      im.src = d.media;
      im.alt = text(d.titleKey, d.title);
      media.appendChild(im);
    }
    // Footer buttons: source code and/or the YouTube page
    var links = $('#projectLinks');
    links.textContent = '';
    if (d.code) {
      var a = document.createElement('a');
      a.className = 'btn btn--ghost btn--small';
      a.href = d.code;
      a.target = '_blank';
      a.rel = 'noopener';
      a.textContent = tr('code');
      links.appendChild(a);
    }
    if (d.youtube) {
      var y = document.createElement('a');
      y.className = 'btn btn--ghost btn--small';
      y.href = 'https://www.youtube.com/watch?v=' + encodeURIComponent(d.youtube);
      y.target = '_blank';
      y.rel = 'noopener';
      y.textContent = tr('youtube');
      links.appendChild(y);
    }
  }
  function closeDialog() {
    if (dlg.open) dlg.close();
  }
  $$('.project__open').forEach(function (btn) {
    btn.addEventListener('click', function () {
      current = btn;
      fillDialog(btn);
      if (typeof dlg.showModal === 'function') dlg.showModal();
      else dlg.setAttribute('open', ''); // old browsers
    });
  });
  $('#projectClose').addEventListener('click', closeDialog);
  dlg.addEventListener('click', function (e) {
    if (e.target === dlg) closeDialog();
  }); // click on the backdrop
  dlg.addEventListener('close', function () {
    $('#projectMedia').textContent = '';
  }); // removes the player, which stops playback
  // #endregion

  // #region 8. Visit counter
  // POST /api/visits counts the visit (the server de-duplicates per visitor); GET only reads the number.
  // sessionStorage remembers that this tab already counted, so reloads do not hit the counter again.
  // The counter stays hidden when the API is unavailable. Open the site with ?debug=1 (or on localhost)
  // to see why: the box then shows a short diagnostic instead of a number.
  (function counter() {
    var preview = location.protocol === 'file:' || /^(localhost|127\.|0\.0\.0\.0)/.test(location.hostname);
    var debug = preview || /[?&]debug=1/.test(location.search);
    var box = $('#visitCounter');
    var counted = false;
    try {
      counted = sessionStorage.getItem('counted') === '1';
    } catch (e) {}
    fetch('/api/visits', { method: counted ? 'GET' : 'POST', cache: 'no-store' })
      .then(function (r) {
        return r.json();
      })
      .then(function (d) {
        try {
          sessionStorage.setItem('counted', '1');
        } catch (e) {}
        if (d && typeof d.count === 'number') {
          var n = $('#visitCount');
          n.dataset.n = d.count; // keep the raw number so a language change can re-format it
          n.textContent = d.count.toLocaleString(LOCALE[lang]);
          $('#visitLabel').textContent = tr('visits');
          box.hidden = false;
        } else if (debug) {
          box.hidden = false;
          $('#visitCount').textContent = '—';
          $('#visitLabel').textContent = preview
            ? tr('preview')
            : d && d.configured === false
              ? 'counter not configured: connect Upstash Redis in Vercel (Storage) and redeploy'
              : 'counter unavailable';
        }
      })
      .catch(function () {
        if (debug) {
          box.hidden = false;
          $('#visitCount').textContent = '—';
          $('#visitLabel').textContent = preview ? tr('preview') : 'no /api/visits (run on Vercel)';
        }
      });
  })();
  // #endregion

  // #region 9. Contact form
  // Flow: client-side validation -> POST /api/contact -> status message.
  // Any failure ends with a mailto: link, so the visitor can always reach me.
  var form = $('#contactForm'),
    statusEl = $('#formStatus'),
    submit = $('#submitButton');
  var EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

  // Shows a translated message under the form. kind: "ok" | "error". withMailto appends the fallback link.
  function setStatus(msgKey, kind, withMailto) {
    statusEl.textContent = '';
    statusEl.className = 'form__status' + (kind ? ' is-' + kind : '');
    statusEl.dataset.msg = msgKey || ''; // stored so applyLanguage() can re-translate it
    if (!msgKey) return;
    statusEl.appendChild(document.createTextNode(tr(msgKey)));
    if (withMailto) {
      statusEl.appendChild(document.createTextNode(' '));
      var a = document.createElement('a');
      a.href =
        'mailto:' +
        EMAIL +
        '?subject=' +
        encodeURIComponent('Portfolio contact') +
        '&body=' +
        encodeURIComponent(form.message.value);
      a.textContent = EMAIL;
      statusEl.appendChild(a);
    }
  }
  // Same rules as the server (api/contact.js): name >= 2, valid email, message >= 10 characters.
  function validate() {
    var ok = true;
    function mark(name, good) {
      var f = form[name].closest('.field');
      f.classList.toggle('is-invalid', !good);
      if (!good) ok = false;
    }
    mark('name', form.name.value.trim().length >= 2);
    mark('email', EMAIL_RE.test(form.email.value.trim()));
    mark('message', form.message.value.trim().length >= 10);
    return ok;
  }
  ['name', 'email', 'message'].forEach(function (n) {
    form[n].addEventListener('input', function () {
      form[n].closest('.field').classList.remove('is-invalid');
    });
  });

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    setStatus('', '');
    if (!validate()) {
      setStatus('form_invalid', 'error');
      var bad = $('.field.is-invalid input, .field.is-invalid textarea', form);
      if (bad) bad.focus();
      return;
    }
    if (location.protocol === 'file:') {
      setStatus('form_local', 'error', true);
      return;
    } // no server when opened from disk
    submit.disabled = true;
    $('span', submit).textContent = tr('sending');
    // "website" is the hidden honeypot field: humans leave it empty, bots fill it.
    var payload = {
      name: form.name.value,
      email: form.email.value,
      phone: form.phone.value,
      message: form.message.value,
      website: form.website.value,
    };
    fetch('/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    })
      .then(function (r) {
        return r
          .json()
          .catch(function () {
            return {};
          })
          .then(function (d) {
            return { status: r.status, data: d };
          });
      })
      .then(function (res) {
        if (res.status === 200 && res.data.ok) {
          form.reset();
          setStatus('form_ok', 'ok');
        } else if (res.status === 422) {
          setStatus('form_invalid', 'error');
        } // server-side validation failed
        else if (res.status === 404 || res.status === 405) {
          setStatus('form_local', 'error', true);
        } // no /api here (static preview)
        else if (res.status === 429) {
          setStatus('form_rate', 'error', true);
        } // rate limit: 5 per hour
        else {
          setStatus('form_down', 'error', true);
          if (window.console) console.warn('contact failed:', res.status, res.data && res.data.reason);
        }
      })
      .catch(function () {
        setStatus('form_net', 'error', true);
      })
      .then(function () {
        submit.disabled = false;
        $('span', submit).textContent = tr('send');
      });
  });
  // #endregion

  // #region 10. Start-up
  $('#year').textContent = new Date().getFullYear();
  applyLanguage();
  // #endregion
})();
